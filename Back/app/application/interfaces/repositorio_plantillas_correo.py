from typing import Any, Protocol
from uuid import UUID


class IRepositorioPlantillasCorreo(Protocol):
    """Acceso a los textos editados de los correos y a los datos de la empresa."""

    async def obtener_plantillas(self) -> dict[str, Any]: ...
    async def obtener_configuracion(self) -> Any | None: ...
    async def guardar_plantilla(self, clave: str, campos: dict[str, str | None], usuario_id: UUID | None) -> Any: ...
    async def eliminar_plantilla(self, clave: str) -> None: ...
    async def guardar_configuracion(self, campos: dict[str, str | None], usuario_id: UUID | None) -> Any: ...
