from typing import Any, Protocol
from uuid import UUID


class IRepositorioUsuarios(Protocol):
    """Protocolo que define el contrato de acceso a datos para Usuarios."""

    async def obtener_por_id(self, id: UUID) -> Any | None: ...
    async def obtener_por_dni(self, dni: str) -> Any | None: ...
    async def obtener_por_email(self, email: str) -> Any | None: ...
    async def crear(self, usuario: Any) -> Any: ...
    async def actualizar_password(self, id: UUID, nuevo_hash: str) -> bool: ...

